import test from "node:test";
import assert from "node:assert/strict";
import {applyItemCorrection,applySourceReview,hasReverifiedSource,reopenManualResolution} from "../public/item-review.js";
import {reverifyEditedMoney} from "../lib/source-reverify.mjs";
const original=()=>({id:"r1",kind:"money",title:"Coffee",amount:0.01,direction:"i_owe",evidence:"You still owe me $0.01 for coffee.",status:"open",txHash:""});
const text="You still owe me $0.01 for coffee.";
const payload=amount=>({text,evidence:text,amount,direction:"i_owe",perspective:"incoming"});
test("correction -> failed source check -> source-supported unpaid state",()=>{
 const item=original();
 assert.equal(applyItemCorrection(item,{title:"Edited coffee",amount:"0.02",direction:"i_owe",status:"needs_review"}).ok,true);
 assert.equal(hasReverifiedSource(item),false);
 const denied=reverifyEditedMoney(payload(0.02));
 assert.equal(denied.supported,false);
 assert.equal(applySourceReview(item,denied).supported,false);
 assert.equal(item.status,"needs_review");
 assert.equal(item.manualReviewOnly,true);
 assert.equal(item.reviewHistory.length,2);
 assert.equal(applyItemCorrection(item,{title:"Adjusted coffee",amount:"0.01",direction:"i_owe",status:"needs_review"}).ok,true);
 const supported=reverifyEditedMoney(payload(0.01));
 assert.equal(supported.supported,true);
 const changed=applySourceReview(item,supported,{now:"2026-10-13T00:45:00Z"});
 assert.equal(changed.ok,true); assert.equal(changed.supported,true);
 assert.equal(item.status,"open");
 assert.equal(item.manualReviewOnly,false);
 assert.equal(hasReverifiedSource(item),true);
 assert.equal(item.sourceVerification.evidence,supported.sourceEvidence);
 assert.equal(item.reviewHistory.at(-1).kind,"source_recheck");
 assert.equal(item.sourceEvidence,text);
 assert.equal(item.evidence,text);
 assert.equal(item.txHash,"");
});
test("any later manual edit clears source authorization until rechecked again",()=>{
 const item=original();
 applyItemCorrection(item,{title:"Reviewed",amount:"0.01",direction:"i_owe",status:"needs_review"});
 applySourceReview(item,reverifyEditedMoney(payload(0.01)));
 assert.equal(hasReverifiedSource(item),true);
 applyItemCorrection(item,{title:"Reviewed again",amount:"0.01",direction:"i_owe",status:"needs_review"});
 assert.equal(item.status,"needs_review");
 assert.equal(item.manualReviewOnly,true);
 assert.equal(hasReverifiedSource(item),false);
 assert.equal(item.sourceVerification,undefined);
});
test("handled outside Owed and dismissed are terminal until explicit re-open",()=>{
 const item=original();
 applyItemCorrection(item,{title:"Coffee repaid outside",amount:"0.01",direction:"i_owe",status:"user_handled"});
 assert.equal(item.status,"user_handled");
 assert.equal(hasReverifiedSource(item),false);
 assert.match(item.contextNote,/not a verified onchain/i);
 assert.equal(reopenManualResolution(item,{now:"2026-10-13T00:50:00Z"}),true);
 assert.equal(item.status,"needs_review");
 assert.equal(item.reviewHistory.at(-1).kind,"reopen_review");
 assert.equal(reopenManualResolution(item),false);
 applyItemCorrection(item,{title:"Coffee dismissed",amount:"0.01",direction:"i_owe",status:"dismissed"});
 assert.equal(item.status,"dismissed");
 assert.equal(reopenManualResolution(item),true);
 assert.equal(item.status,"needs_review");
});
test("settled, pending and locked group transfers are never altered by recheck",()=>{
 const item={...original(),status:"pending",txHash:"0x"+"a".repeat(64)};
 assert.equal(applySourceReview(item,reverifyEditedMoney(payload(0.01))).ok,false);
 assert.equal(item.status,"pending");
});
